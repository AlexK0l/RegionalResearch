async function runResearchMicroBatch({
  client,
  region,
  stageIndex,
  branch,
  branchIndex,
  branches,
  scopes,
  extraContext = "",
  alreadyFound = []
}) {
  const selectedScopes = discoveryScopesForBranch(stageIndex, branchIndex, scopes);
  const merged = emptyResearchResult();
  const knownNames = [...alreadyFound];
  let successCount = 0;
  let firstError = null;
  let lowYieldStreak = 0;
  let regionalYield = null;
  let firstLocalYield = null;

  for (let scopeIndex = 0; scopeIndex < selectedScopes.length; scopeIndex++) {
    if (
      scopeIndex >= 2 &&
      firstLocalYield &&
      !discoveryGeoExpansionWorthwhile(firstLocalYield) &&
      !discoveryGeoExpansionWorthwhile(regionalYield)
    ) {
      console.log("[DISCOVERY_GEO_EXPANSION_SKIP] " + JSON.stringify({
        stage: stageIndex + 1,
        branch: branchIndex + 1,
        reason: "regional_and_first_local_scope_not_productive_enough",
        regional_quality_yield: regionalYield,
        first_local_quality_yield: firstLocalYield,
        skipped_scopes: selectedScopes.length - scopeIndex
      }));
      break;
    }

    const scope = selectedScopes[scopeIndex];
    const beforeKnown = [...knownNames];
    const knownContext = knownNames.length
      ? `УЖЕ НАЙДЕННЫЕ В ЭТОМ РЕГИОНЕ — не трать web_search на повторное обнаружение этих организаций; ищи новые: ${knownNames.join("; ")}`
      : "";

    try {
      const value = await askResearch(
        client,
        compactDiscoveryPrompt({
          region,
          stageIndex,
          branch,
          branchIndex,
          totalBranches: branches.length,
          scope,
          extraContext: [extraContext, knownContext].filter(Boolean).join("\n")
        }),
        RESEARCH_MICRO_MAX_OUTPUT_TOKENS,
        `этап ${stageIndex + 1} | ветка ${branchIndex + 1}/${branches.length} | ${branch} | ${scope}`
      );

      const normalized = normalize(value);
      const yieldStats = discoveryYieldStats(normalized, beforeKnown);
      const added = yieldStats.newOrganizations;
      if (scopeIndex === 0) regionalYield = yieldStats;
      if (scopeIndex === 1) firstLocalYield = yieldStats;
      console.log("[DISCOVERY_SCOPE_RESULT] " + JSON.stringify({
        stage: stageIndex + 1,
        branch: branchIndex + 1,
        branch_name: branch,
        scope_index: scopeIndex + 1,
        scope,
        rows: diagnosticRowCount(normalized),
        new_organizations: added,
        quality_yield: yieldStats,
        token_usage_cumulative: tokenUsageSnapshot(client),
        companies: diagnosticDiscoveryRows(normalized)
      }));
      appendResearchResult(
        merged,
        normalized,
        `branch-${branchIndex + 1}-scope-${scopeIndex + 1}`
      );
      mergeKnownOrganizationNames(knownNames, normalized);
      successCount++;

      // Первый scope всегда региональный. Низкий yield локальных scope подряд означает,
      // что дальнейшее географическое дробление в этой ветке даёт в основном повторы.
      if (scopeIndex > 0) {
        const threshold = adaptiveDiscoveryLowYieldThreshold(knownNames.length);
        const streakLimit = adaptiveDiscoveryLowYieldStreak(selectedScopes.length);
        lowYieldStreak =
          added <= threshold || discoveryQualityIsLow(yieldStats)
            ? lowYieldStreak + 1
            : 0;
        if (
          lowYieldStreak >= streakLimit &&
          scopeIndex + 1 < selectedScopes.length
        ) {
          console.log("[DISCOVERY_SCOPE_STOP] " + JSON.stringify({
            stage: stageIndex + 1,
            branch: branchIndex + 1,
            processed_scopes: scopeIndex + 1,
            total_scopes: selectedScopes.length,
            last_added: added,
            threshold,
            streak_limit: streakLimit
          }));
          break;
        }
      }
    } catch (error) {
      if (isWebBudgetStop(error)) throw error;
      if (!firstError) firstError = error;
    }
  }

  if (!successCount && firstError) throw firstError;
  return merged;
}

