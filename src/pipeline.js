function normalizeInn(value) {
  const digits = String(value || "").replace(/\D/g, "");
  return digits.length === 10 || digits.length === 12 ? digits : "";
}

function normalizeOrgKey(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/\b(общество с ограниченной ответственностью|публичное акционерное общество|открытое акционерное общество|закрытое акционерное общество|акционерное общество|индивидуальный предприниматель)\b/g, " ")
    .replace(/[«»"'.,()]/g, " ")
    .replace(/\b(ооо|ао|пао|зао|оао|ип)\b/g, " ")
    .replace(/[^a-zа-яё0-9]+/gi, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function normalizePlaceKey(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[^a-zа-яё0-9]+/gi, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function evidenceDomains(row) {
  const urls = Array.isArray(row?.__evidence?.source_urls)
    ? row.__evidence.source_urls
    : [];
  const domains = new Set();
  for (const raw of urls) {
    try {
      const host = new URL(String(raw)).hostname
        .toLowerCase()
        .replace(/^www\./, "");
      if (host) domains.add(host);
    } catch {}
  }
  return domains;
}

function buildIdentityClusters(candidates) {
  const parent = candidates.map((_, i) => i);

  const find = (x) => {
    while (parent[x] !== x) {
      parent[x] = parent[parent[x]];
      x = parent[x];
    }
    return x;
  };
  const union = (a, b) => {
    const ra = find(a);
    const rb = find(b);
    if (ra !== rb) parent[rb] = ra;
  };

  const byExactName = new Map();
  const byNamePlace = new Map();
  const byDomain = new Map();

  for (let i = 0; i < candidates.length; i++) {
    const row = candidates[i]?.data || {};
    const org = normalizeOrgKey(row["Организация"]);
    const place = normalizePlaceKey(row["Город/район"]);

    if (org) {
      const exact = byExactName.get(org);
      if (exact !== undefined) union(i, exact);
      else byExactName.set(org, i);

      if (place) {
        const key = `${org}|${place}`;
        const known = byNamePlace.get(key);
        if (known !== undefined) union(i, known);
        else byNamePlace.set(key, i);
      }
    }

    for (const domain of evidenceDomains(row)) {
      // Один домен сам по себе не доказывает дубль. Объединяем по домену
      // только если нормализованное название также совпадает.
      if (!org) continue;
      const key = `${domain}|${org}`;
      const known = byDomain.get(key);
      if (known !== undefined) union(i, known);
      else byDomain.set(key, i);
    }
  }

  const groups = new Map();
  for (let i = 0; i < candidates.length; i++) {
    const root = find(i);
    if (!groups.has(root)) groups.set(root, []);
    groups.get(root).push(candidates[i]);
  }

  return [...groups.values()].map((items, index) => ({
    cluster_id: `i${String(index + 1).padStart(6, "0")}`,
    items
  }));
}

function extractInnFromEvidenceNotes(row) {
  const notes = Array.isArray(row?.__evidence?.notes) ? row.__evidence.notes : [];
  const candidates = new Set();
  for (const note of notes) {
    const text = String(note || "");
    for (const match of text.matchAll(/ИНН\s*[:№-]?\s*(\d{10}|\d{12})/gi)) {
      const inn = normalizeInn(match[1]);
      if (inn) candidates.add(inn);
    }
  }
  return candidates.size === 1 ? [...candidates][0] : "";
}

function extractInnFromEvidenceUrls(row) {
  const urls = Array.isArray(row?.__evidence?.source_urls) ? row.__evidence.source_urls : [];
  const candidates = new Set();

  for (const raw of urls) {
    const text = String(raw || "");
    const decoded = (() => {
      try { return decodeURIComponent(text); } catch { return text; }
    })();

    const patterns = [
      /(?:^|[^a-z])inn[-_/:= ]*(\d{10}|\d{12})(?:\D|$)/gi,
      /(?:^|[^a-zа-я])инн[-_/:= ]*(\d{10}|\d{12})(?:\D|$)/gi
    ];
    for (const pattern of patterns) {
      for (const match of decoded.matchAll(pattern)) {
        const inn = normalizeInn(match[1]);
        if (inn) candidates.add(inn);
      }
    }
  }

  return candidates.size === 1 ? [...candidates][0] : "";
}

function clusterEvidenceIdentity(cluster) {
  const items = cluster?.items || [];
  const inns = new Set();
  const names = new Set();
  const places = new Set();
  const domains = new Set();

  for (const item of items) {
    const row = item?.data || {};
    const directInn = normalizeInn(row["ИНН"]);
    const evidenceInn = extractInnFromEvidenceNotes(row);
    const urlInn = extractInnFromEvidenceUrls(row);
    if (directInn) inns.add(directInn);
    if (evidenceInn) inns.add(evidenceInn);
    if (urlInn) inns.add(urlInn);

    const name = normalizeOrgKey(row["Организация"]);
    if (name) names.add(name);

    const place = normalizePlaceKey(row["Город/район"]);
    if (place) places.add(place);

    for (const domain of evidenceDomains(row)) domains.add(domain);
  }

  return {
    inns: [...inns],
    names: [...names],
    places: [...places],
    domains: [...domains]
  };
}

function looksAmbiguousOrganizationName(value) {
  const raw = String(value || "").trim().toLowerCase();
  const normalized = normalizeOrgKey(value);
  if (!normalized) return true;

  const genericTokens = new Set([
    "тандем","транзит","ресурс","ресурсы","агро","карьер","сервис","логистика",
    "транспорт","строй","групп","группа","центр","торг","торговый","компания",
    "поставка","снабжение","экспресс","авто","спецтехника","техно","альянс"
  ]);
  const tokens = normalized.split(/\s+/).filter(Boolean);

  if (tokens.length === 1 && genericTokens.has(tokens[0])) return true;
  if (/^(сервис|центр|площадка|направление|филиал)\b/.test(raw)) return true;
  if (/основани[ея]\s+[abc]/i.test(raw)) return true;

  return false;
}

function clusterNeedsIdentityWebSearch(cluster) {
  const items = cluster?.items || [];
  if (!items.length) return false;

  const row = items[0]?.data || {};
  const identity = clusterEvidenceIdentity(cluster);

  // Конфликтующие ИНН требуют внешней проверки при любом размере кластера.
  if (identity.inns.length > 1) return true;

  // Один подтверждённый ИНН уже достаточен и для singleton, и для повторных
  // упоминаний: повторно искать тот же ИНН через web не нужно.
  if (identity.inns.length === 1) return false;

  const org = String(row["Организация"] || "").trim();
  if (looksAmbiguousOrganizationName(org)) return true;

  if (items.length > 1) {
    const normalizedNames = new Set(
      items.map((item) => normalizeOrgKey(item?.data?.["Организация"])).filter(Boolean)
    );
    const places = items
      .map((item) => normalizePlaceKey(item?.data?.["Город/район"]))
      .filter(Boolean);
    const sameNonEmptyPlace =
      places.length === items.length && new Set(places).size === 1;

    const domainSets = items.map((item) => evidenceDomains(item?.data || {}));
    let sharedDomain = false;
    if (domainSets.length && domainSets.every((set) => set.size)) {
      sharedDomain = [...domainSets[0]].some((domain) =>
        domainSets.slice(1).every((set) => set.has(domain))
      );
    }

    // Повторные упоминания одного и того же недвусмысленного названия уже
    // достаточно связаны, если совпадает география либо есть общий evidence-domain.
    // Dedupe ниже объединит их детерминированно; web-search здесь не добавляет
    // достаточной ценности, чтобы оправдать отдельный identity-вызов.
    if (normalizedNames.size === 1 && (sameNonEmptyPlace || sharedDomain)) {
      return false;
    }

    return true;
  }

  // Несколько разных доменов при singleton часто означают агрегаторы/посредников
  // или неочевидную юридическую идентичность.
  if (identity.domains.length > 2) return true;

  return false;
}

function resolveClusterWithoutWeb(cluster) {
  const identity = clusterEvidenceIdentity(cluster);
  const inn = identity.inns.length === 1 ? identity.inns[0] : "";
  return cluster.items.map((item) => {
    const data = { ...(item?.data || {}) };
    if (inn) {
      data["ИНН"] = inn;
      const existingEvidence = data.__evidence || {};
      data.__evidence = {
        ...existingEvidence,
        source_urls: Array.isArray(existingEvidence.source_urls)
          ? [...new Set(existingEvidence.source_urls.map(String).filter(Boolean))]
          : [],
        notes: [
          ...(Array.isArray(existingEvidence.notes) ? existingEvidence.notes : []),
          `Identity без нового web-search: ИНН ${inn} извлечён из уже собранного evidence.`
        ]
      };
    }
    return { ...item, data };
  });
}

