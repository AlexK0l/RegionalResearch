function applyFinalQa(records, qa) {
  const allowedSheets = new Set(["direct_buyers", "intermediaries", "leasing"]);
  const allowedFields = new Set([...COLS, "__comment", "__decision", "__decision_reason", "__evidence", "__final_grade"]);
  const removeIds = new Set(Array.isArray(qa?.remove_ids) ? qa.remove_ids.map(String) : []);
  const moves = new Map();

  for (const item of Array.isArray(qa?.moves) ? qa.moves : []) {
    const id = String(item?.id || "");
    const sheet = String(item?.sheet || "");
    if (id && allowedSheets.has(sheet)) moves.set(id, sheet);
  }

  const patches = new Map();
  for (const item of Array.isArray(qa?.patches) ? qa.patches : []) {
    const id = String(item?.id || "");
    if (!id || !item?.fields || typeof item.fields !== "object") continue;
    const filtered = {};
    for (const [key, value] of Object.entries(item.fields)) {
      if (allowedFields.has(key)) filtered[key] = value ?? "";
    }
    if (Object.keys(filtered).length) patches.set(id, filtered);
  }

  const result = {
    direct_buyers: [],
    intermediaries: [],
    leasing: [],
    statistics: []
  };

  for (const record of records) {
    if (removeIds.has(record.id)) continue;
    const row = { ...record.row, ...(patches.get(record.id) || {}) };
    const sheet = moves.get(record.id) || record.sheet;
    if (allowedSheets.has(sheet)) result[sheet].push(row);
  }

  return result;
}

function mergeQaRecordRows(records) {
  const first = records[0];
  const mergedRow = { ...(first?.row || {}) };
  const urls = [];
  const notes = [];

  for (const record of records) {
    const row = record?.row || {};
    for (const col of COLS) {
      const current = String(mergedRow[col] || "").trim();
      const incoming = String(row[col] || "").trim();
      if (!current && incoming) mergedRow[col] = incoming;
    }

    const segments = [mergedRow["Техника/сегмент"], row["Техника/сегмент"]]
      .flatMap((value) => String(value || "").split("|"))
      .map((value) => value.trim())
      .filter(Boolean);
    if (segments.length) mergedRow["Техника/сегмент"] = [...new Set(segments)].join(" | ");

    const evidence = row.__evidence || {};
    for (const url of Array.isArray(evidence.source_urls) ? evidence.source_urls : []) {
      if (url) urls.push(String(url));
    }
    for (const note of Array.isArray(evidence.notes) ? evidence.notes : []) {
      if (note) notes.push(String(note));
    }
  }

  mergedRow.__evidence = {
    source_urls: [...new Set(urls)],
    notes: [...new Set(notes)]
  };

  return {
    ...first,
    row: mergedRow
  };
}

const ORG_IDENTITY_STOP_TOKENS = new Set([
  // Universal legal forms.
  "ооо", "ао", "пао", "оао", "зао", "ип", "спк", "схпк", "согбу",
  "фгуп", "муп", "гуп", "нко",
  // Universal structural / geographic descriptors.
  "группа", "групп", "компания", "компаний", "филиал", "проект",
  "область", "области", "край", "республика", "район", "округ",
  "автономная", "автономный", "региональный", "город"
]);

function regionIdentityTokens(region) {
  return normalizePlaceKey(region)
    .split(/\s+/)
    .filter((token) => token.length >= 3 && !ORG_IDENTITY_STOP_TOKENS.has(token));
}

function isRegionIdentityToken(token, region) {
  const value = String(token || "").toLowerCase();
  for (const regional of regionIdentityTokens(region)) {
    if (value === regional) return true;
    if (regional.length >= 6) {
      const prefix = regional.slice(0, Math.min(7, regional.length));
      if (value.length >= prefix.length && value.startsWith(prefix)) return true;
    }
  }
  return false;
}

function organizationIdentityTokens(value, region = "") {
  return normalizeOrgKey(value)
    .split(/\s+/)
    .filter((token) =>
      token.length >= 2 &&
      !ORG_IDENTITY_STOP_TOKENS.has(token) &&
      !isRegionIdentityToken(token, region)
    );
}

function organizationNamesCompatible(a, b, region = "") {
  const left = normalizeOrgKey(a);
  const right = normalizeOrgKey(b);
  if (!left || !right) return false;
  if (left === right) return true;

  const lt = organizationIdentityTokens(a, region);
  const rt = organizationIdentityTokens(b, region);
  if (!lt.length || !rt.length) return false;

  const ls = new Set(lt);
  const rs = new Set(rt);
  const shared = [...ls].filter((token) => rs.has(token));
  const minSize = Math.min(ls.size, rs.size);

  // Alias matching must never be decided by one shared token.
  // Exact normalized names were handled above; all fuzzy name matches now
  // require at least two shared non-structural tokens with strong overlap.
  // Industry vocabulary is intentionally not hard-coded here.
  if (
    shared.length >= 2 &&
    minSize >= 2 &&
    shared.length / minSize >= 0.67
  ) return true;

  return false;
}

function organizationAcronymCandidates(value, region = "") {
  const normalized = normalizeOrgKey(value);
  const geoStop = new Set([
    "ооо", "ао", "пао", "оао", "зао", "ип", "спк", "схпк", "согбу",
    "область", "области", "край", "республика", "район", "района", "округ", "город"
  ]);
  const tokens = normalized
    .split(/\s+/)
    .filter((token) =>
      token.length >= 2 &&
      !geoStop.has(token) &&
      !isRegionIdentityToken(token, region)
    );

  const acronyms = new Set();

  // Only derive a real initials-based acronym from a multi-word name.
  // Treating every short token ("агро", "транс", "центр", "строй", etc.)
  // as an acronym caused unrelated companies to collapse into one group.
  if (tokens.length >= 2 && tokens.length <= 5) {
    const initials = tokens.map((token) => token[0]).join("");
    if (initials.length >= 2 && initials.length <= 5) acronyms.add(initials);
  }

  return acronyms;
}

function recordsShareEvidenceDomain(a, b) {
  const left = evidenceDomains(a?.row || {});
  const right = evidenceDomains(b?.row || {});
  for (const domain of left) {
    if (right.has(domain)) return true;
  }
  return false;
}

function organizationRoleSignature(value) {
  const normalized = normalizeOrgKey(value);
  return {
    management:
      /(^|\s)ук(\s|$)/.test(normalized) ||
      normalized.includes("управляющая компания"),
    project: /(^|\s)проект(\s|$)/.test(normalized),
    group:
      /(^|\s)гк(\s|$)/.test(normalized) ||
      /(^|\s)группа(\s|$)/.test(normalized) ||
      /(^|\s)холдинг(\s|$)/.test(normalized),
    branch:
      /(^|\s)филиал(\s|$)/.test(normalized) ||
      /(^|\s)подразделени/.test(normalized),
    brand:
      /(^|\s)бренд(\s|$)/.test(normalized) ||
      normalized.includes("торговая марка")
  };
}

function materiallyDifferentRoleSignatures(a, b) {
  const left = organizationRoleSignature(a);
  const right = organizationRoleSignature(b);
  return Object.keys(left).some((key) => Boolean(left[key]) !== Boolean(right[key]));
}

function compoundOrganizationSegments(value) {
  return String(value || "")
    .split(/[\/|;]/)
    .map((part) => part.trim())
    .filter(Boolean);
}

function safeAliasIdentityCompatible(a, b, region = "") {
  const aInn = normalizeInn(a?.row?.["ИНН"]);
  const bInn = normalizeInn(b?.row?.["ИНН"]);

  // Alias pass must never override the stricter INN pass.
  // If both records already have confirmed INNs, they were either merged safely
  // in splitInnGroupByCompatibleIdentity or intentionally kept apart.
  if (aInn && bInn) return false;

  const aName = String(a?.row?.["Организация"] || "").trim();
  const bName = String(b?.row?.["Организация"] || "").trim();
  if (!aName || !bName) return false;

  // Compound fields are handled structurally rather than by a blanket slash rule.
  // If a row names several materially different variants, every non-trivial
  // segment must independently agree with the other organization's name.
  if (!aInn || !bInn) {
    for (const [compound, other] of [[aName, bName], [bName, aName]]) {
      const segments = compoundOrganizationSegments(compound);
      if (segments.length > 1) {
        const allCompatible = segments.every((segment) =>
          organizationNamesCompatible(segment, other, region) ||
          normalizeOrgKey(segment) === normalizeOrgKey(other)
        );
        if (!allCompatible) return false;
      }
    }
  }

  // Structural role changes (management company, project, group, branch, brand)
  // are evidence of a relationship, not proof of one legal entity.
  if (!aInn && !bInn && materiallyDifferentRoleSignatures(aName, bName)) {
    return false;
  }

  if (organizationNamesCompatible(aName, bName, region)) return true;

  // Long official name vs stable acronym, e.g. Regional Leasing Center / RLC.
  const aTokens = new Set(normalizeOrgKey(aName).split(/\s+/).filter(Boolean));
  const bTokens = new Set(normalizeOrgKey(bName).split(/\s+/).filter(Boolean));
  const aAcronyms = organizationAcronymCandidates(aName, region);
  const bAcronyms = organizationAcronymCandidates(bName, region);
  for (const acronym of aAcronyms) {
    if (bTokens.has(acronym) && acronym.length >= 3) return true;
  }
  for (const acronym of bAcronyms) {
    if (aTokens.has(acronym) && acronym.length >= 3) return true;
  }

  // Evidence-domain overlap is intentionally NOT enough to merge legal entities.
  // Many unrelated companies share marketplace, registry or industry domains.
  // If names are not compatible above, keep the records separate.

  return false;
}

function conservativeAliasDedupe(records, diagnostics = null, region = "") {
  const consumed = new Set();
  const merged = [];
  let aliasMerged = 0;

  // Greedy representative matching avoids transitive bridge merges:
  // A~B and B~C no longer implies A~C.
  for (let i = 0; i < records.length; i++) {
    if (consumed.has(i)) continue;

    const group = [records[i]];
    consumed.add(i);

    for (let j = i + 1; j < records.length; j++) {
      if (consumed.has(j)) continue;

      // Every candidate must be directly compatible with the representative.
      if (!safeAliasIdentityCompatible(records[i], records[j], region)) continue;

      // If the candidate has an INN and the representative does not, do not let
      // that candidate turn the group into a bridge for other legal entities.
      group.push(records[j]);
      consumed.add(j);
    }

    if (group.length === 1) {
      merged.push(group[0]);
      continue;
    }

    const inns = [...new Set(
      group.map((record) => normalizeInn(record?.row?.["ИНН"])).filter(Boolean)
    )];

    if (inns.length > 1) {
      console.log("[DEDUPE_ALIAS_CONFLICT] " + JSON.stringify({
        inns,
        organizations: group.map((record) =>
          String(record?.row?.["Организация"] || "").trim()
        )
      }));
      merged.push(...group);
      continue;
    }

    aliasMerged += group.length - 1;
    recordDedupeMerge(diagnostics, "alias", group, inns[0] || "");
    console.log("[DEDUPE_ALIAS_MERGE] " + JSON.stringify({
      inn: inns[0] || "",
      organizations: group.map((record) =>
        String(record?.row?.["Организация"] || "").trim()
      )
    }));
    merged.push(mergeQaRecordRows(group));
  }

  return { records: merged, aliasMerged };
}

function splitInnGroupByCompatibleIdentity(records, inn, region = "") {
  const groups = [];

  for (const record of records) {
    const name = String(record?.row?.["Организация"] || "").trim();
    let target = null;

    for (const group of groups) {
      const representative = String(group[0]?.row?.["Организация"] || "").trim();
      if (organizationNamesCompatible(name, representative, region)) {
        target = group;
        break;
      }
    }

    if (target) target.push(record);
    else groups.push([record]);
  }

  if (groups.length > 1) {
    console.log("[DEDUPE_INN_CONFLICT] " + JSON.stringify({
      inn,
      organizations: groups.map((group) =>
        [...new Set(group.map((record) => String(record?.row?.["Организация"] || "").trim()).filter(Boolean))]
      )
    }));
  }

  return groups;
}

function recordDedupeMerge(diagnostics, type, records, key = "") {
  if (!diagnostics || !Array.isArray(records) || records.length < 2) return;
  if (!Array.isArray(diagnostics.merges)) diagnostics.merges = [];
  diagnostics.merges.push({
    type,
    key,
    organizations: records.map((record) =>
      String(record?.row?.["Организация"] || "").trim()
    ).filter(Boolean),
    inns: [...new Set(
      records.map((record) => normalizeInn(record?.row?.["ИНН"])).filter(Boolean)
    )]
  });
}

function deterministicGlobalDedupe(records, diagnostics = null, region = "") {
  const output = [];
  const unresolved = [];
  const byInn = new Map();

  // Confirmed INN is the strongest deterministic identity key and must work
  // across legal-name variants and source sheets.
  for (const record of records) {
    const inn = normalizeInn(record?.row?.["ИНН"]);
    if (!inn) {
      unresolved.push(record);
      continue;
    }
    if (!byInn.has(inn)) byInn.set(inn, []);
    byInn.get(inn).push(record);
  }

  for (const [inn, innGroup] of byInn.entries()) {
    const compatibleGroups = splitInnGroupByCompatibleIdentity(innGroup, inn, region);
    for (const compatibleGroup of compatibleGroups) {
      if (compatibleGroup.length > 1) {
        recordDedupeMerge(diagnostics, "confirmed_inn", compatibleGroup, inn);
      }
      output.push(
        compatibleGroup.length === 1
          ? compatibleGroup[0]
          : mergeQaRecordRows(compatibleGroup)
      );
    }
  }

  // Rows without confirmed INN are deduplicated conservatively by normalized
  // organization name. Ambiguous generic names also require matching place.
  const grouped = new Map();
  const singles = [];

  for (const record of unresolved) {
    const row = record?.row || {};
    const org = normalizeOrgKey(row["Организация"]);
    if (!org) {
      singles.push(record);
      continue;
    }

    const ambiguous = looksAmbiguousOrganizationName(row["Организация"]);
    const place = ambiguous ? normalizePlaceKey(row["Город/район"]) : "";
    const key = ambiguous ? `org:${org}|place:${place}` : `org:${org}`;
    if (!grouped.has(key)) grouped.set(key, []);
    grouped.get(key).push(record);
  }

  output.push(...singles);
  for (const [key, group] of grouped.entries()) {
    if (group.length > 1) recordDedupeMerge(diagnostics, "normalized_name", group, key);
    output.push(group.length === 1 ? group[0] : mergeQaRecordRows(group));
  }

  const aliasPass = conservativeAliasDedupe(output, diagnostics, region);
  output.length = 0;
  output.push(...aliasPass.records);
  if (aliasPass.aliasMerged) {
    console.log("[DEDUPE_ALIAS_SUMMARY] " + JSON.stringify({
      merged: aliasPass.aliasMerged,
      after: output.length
    }));
  }

  // Stable ordering makes repeated qualification byte-for-byte reproducible.
  output.sort((a, b) => {
    const ao = normalizeOrgKey(a?.row?.["Организация"]);
    const bo = normalizeOrgKey(b?.row?.["Организация"]);
    return ao.localeCompare(bo, "ru") ||
      normalizePlaceKey(a?.row?.["Город/район"]).localeCompare(
        normalizePlaceKey(b?.row?.["Город/район"]),
        "ru"
      ) ||
      String(a?.canonical_id || "").localeCompare(String(b?.canonical_id || ""));
  });

  return output.map((record, index) => ({
    ...record,
    id: `q${String(index + 1).padStart(6, "0")}`
  }));
}

function finalQualificationInput(records) {
  return records.map((record) => ({
    id: record.id,
    sheet: record.sheet,
    canonical_id: record.canonical_id,
    organization: record?.row?.["Организация"] || "",
    city: record?.row?.["Город/район"] || "",
    segment: record?.row?.["Техника/сегмент"] || "",
    basis_summary: record?.row?.["Основание"] || "",
    inn: record?.row?.["ИНН"] || "",
    evidence: record?.row?.__evidence || { source_urls: [], notes: [] }
  }));
}

function qualificationText(record) {
  const row = record?.row || {};
  const evidence = row.__evidence || {};
  return [
    row["Организация"],
    row["Город/район"],
    row["Техника/сегмент"],
    row["Основание"],
    ...(Array.isArray(evidence.notes) ? evidence.notes : [])
  ]
    .map((value) => String(value || "").toLowerCase())
    .join("\n")
    .replace(/ё/g, "е");
}

function qualificationEvidenceNotes(record) {
  const notes = record?.row?.__evidence?.notes;
  return (Array.isArray(notes) ? notes : [])
    .map((value) => String(value || "").toLowerCase().replace(/ё/g, "е").trim())
    .filter(Boolean);
}

function hasAnyPattern(text, patterns) {
  return patterns.some((pattern) => pattern.test(text));
}

