function canonicalizeCandidates(candidates, region = "") {
  const parent = candidates.map((_, i) => i);
  const rank = candidates.map(() => 0);

  const find = (x) => {
    while (parent[x] !== x) {
      parent[x] = parent[parent[x]];
      x = parent[x];
    }
    return x;
  };

  const union = (a, b) => {
    let ra = find(a);
    let rb = find(b);
    if (ra === rb) return;
    if (rank[ra] < rank[rb]) [ra, rb] = [rb, ra];
    parent[rb] = ra;
    if (rank[ra] === rank[rb]) rank[ra]++;
  };

  const innOwners = new Map();

  for (let i = 0; i < candidates.length; i++) {
    const row = candidates[i]?.data || {};
    const inn = normalizeInn(row["ИНН"]);
    if (inn) {
      const owners = innOwners.get(inn) || [];
      const name = String(row["Организация"] || "").trim();
      let compatibleOwner = null;

      for (const ownerIndex of owners) {
        const ownerName = String(candidates[ownerIndex]?.data?.["Организация"] || "").trim();
        if (organizationNamesCompatible(name, ownerName, region)) {
          compatibleOwner = ownerIndex;
          break;
        }
      }

      if (compatibleOwner !== null) {
        union(i, compatibleOwner);
      } else {
        if (owners.length) {
          console.log("[CANONICAL_INN_CONFLICT] " + JSON.stringify({
            inn,
            organization: name,
            existing_organizations: owners.map((ownerIndex) =>
              String(candidates[ownerIndex]?.data?.["Организация"] || "").trim()
            )
          }));
        }
        owners.push(i);
        innOwners.set(inn, owners);
      }
    }

    // Без подтвержденного ИНН строки не объединяем программно только по названию/городу.
    // Одинаковый ИНН тоже не схлопывает явно несовместимые названия на этом раннем слое.
  }

  const groups = new Map();
  for (let i = 0; i < candidates.length; i++) {
    const root = find(i);
    if (!groups.has(root)) groups.set(root, []);
    groups.get(root).push(candidates[i]);
  }

  return [...groups.values()].map((evidence, index) => ({
    canonical_id: `k${String(index + 1).padStart(6, "0")}`,
    candidate_ids: evidence.map((x) => x.candidate_id),
    source_steps: [...new Set(evidence.map((x) => x.source_step))],
    source_sheets: [...new Set(evidence.map((x) => x.source_sheet))],
    evidence
  }));
}

function mergedEvidenceFromCanonical(canonical) {
  const sourceUrls = [];
  const notes = [];
  for (const evidenceItem of canonical?.evidence || []) {
    const ev = evidenceItem?.data?.__evidence || {};
    for (const url of Array.isArray(ev.source_urls) ? ev.source_urls : []) {
      if (url) sourceUrls.push(String(url));
    }
    for (const note of Array.isArray(ev.notes) ? ev.notes : []) {
      if (note) notes.push(String(note));
    }
  }
  return {
    source_urls: [...new Set(sourceUrls)],
    notes: [...new Set(notes)]
  };
}

