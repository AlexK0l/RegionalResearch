function deterministicQualificationDecision(record) {
  const text = qualificationText(record);
  const notes = qualificationEvidenceNotes(record);
  const priorityTarget = hasAnyPattern(text, QUAL_PRIORITY_TARGET_PATTERNS);
  const generalTarget =
    hasAnyPattern(text, QUAL_GENERAL_TARGET_PATTERNS) &&
    hasAnyPattern(text, QUAL_GENERAL_FLOW_PATTERNS);
  const target = priorityTarget || generalTarget;
  const heavy = hasAnyPattern(text, QUAL_HEAVY_PATTERNS);
  const transport = hasAnyPattern(text, QUAL_TRANSPORT_PATTERNS);

  const speculative = /потенциал|перспектив|возможн|может использ|может эксплуат|вероятн|предполож|целевой сегмент|подходит для/;
  const negativeAEvidence =
    /не подтвержд(ен|ена|ено|ены|ает|ают|ается|аются)|нет подтвержден|нет достаточн|не найден|не указа[нн]|требует дополнительн|требуется дополнительн|уровень b|а не a|собственн.{0,40}(парк|эксплуатац).{0,40}не подтвержд|доказательств.{0,80}нет|прямых сведений.{0,80}не найден/;
  const farmImplementOnly =
    /(прицепн.{0,20}агрегат|плуг|сеялк|опрыскивател|разбрасывател).{0,120}/;
  const priorityTrailerModel =
    /(тонар\s*\d{3,5}|grunwald\s*[a-zа-я0-9-]+|kogel\s*[a-zа-я0-9-]+|schmitz\s*[a-zа-я0-9-]+|wielton\s*[a-zа-я0-9-]+|krone\s*[a-zа-я0-9-]+|пс[- ]?\d{1,3}[а-яa-z-]*|пст[- ]?\d{1,3}[а-яa-z-]*|ts\s*\d{2,3})/i;
  const genericTrailerIdentification =
    /((полуприцеп|прицеп).{0,50}(марка|модель|тип|серия|идентификатор).{0,50}[a-zа-я0-9-]{2,})|((марка|модель|тип|серия).{0,50}[a-zа-я0-9-]{2,}.{0,50}(полуприцеп|прицеп))/i;
  const ceTrailerJob =
    /(водител|ваканси).{0,50}(категори.{0,8}(е|ce|cе)).{0,120}(полуприцеп|прицеп|тонар)|((полуприцеп|прицеп|тонар).{0,120}(водител|категори.{0,8}(е|ce|cе)))/;
  const trailerFleet =
    /(парк|автопарк|на балансе|в собственности|имеет|эксплуатирует|эксплуатаци).{0,100}(полуприцеп|прицеп|тонар)|((полуприцеп|прицеп|тонар).{0,100}(парк|автопарк|на балансе|в собственности|эксплуатирует|эксплуатаци))/;
  // Объявление об услуге ремонта/обслуживания не подтверждает выполненный
  // ремонт конкретной техники. Не приравниваем каталог сервиса к сделке.
  const trailerCommerce =
    /(продает|продаем|продажа|лизинг|лизингует|сдает в аренду|аренда).{0,100}(полуприцеп|прицеп|тонар)|((полуприцеп|прицеп|тонар).{0,100}(продает|продаем|продажа|лизинг|лизингует|сдает в аренду|аренда))/;
  const serviceOffering =
    /(сервис|сто|автосервис|ремонт|обслужив|диагностик|услуг|каталог|карточк|специализац)/;
  const specificServiceEvent =
    /(выполн(ен|ены|ила|или)|отремонтирован|проведен.{0,25}ремонт|заказ.наряд|акт выполненн|договор.{0,40}ремонт|контракт.{0,40}ремонт|закупк.{0,40}ремонт|тендер.{0,40}ремонт|клиент.{0,70}(полуприцеп|прицеп)|заказчик.{0,70}(полуприцеп|прицеп))/;
  const serviceMarketingOnly =
    /(оказыва.{0,30}услуг|предлага.{0,30}(ремонт|услуг)|перечень услуг|указан.{0,40}(ремонт|услуг)|заявлен.{0,40}(ремонт|услуг)|карточк.{0,70}ремонт|специализиру.{0,50}ремонт)/;

  let aEvidence = "";

  for (const note of notes) {
    if (speculative.test(note) || negativeAEvidence.test(note)) continue;

    const cargoTrailerMention =
      /(полуприцеп|прицеп[- ]?(зерновоз|самосвал)|самосвальн.{0,20}прицеп|тонар|kogel|krone|schmitz|wielton|grunwald|пс[- ]?\d|пст[- ]?\d|пптс[- ]?\d)/i.test(note);
    if (farmImplementOnly.test(note) && !cargoTrailerMention) continue;

    const trailer = hasAnyPattern(note, QUAL_TRAILER_PATTERNS);
    const trailerAction = hasAnyPattern(note, QUAL_TRAILER_ACTION_PATTERNS);
    const explicitVinOrPlate =
      /(vin|госномер|гос номер).{0,60}(полуприцеп|прицеп)|(полуприцеп|прицеп).{0,60}(vin|госномер|гос номер)/.test(note);
    const tractorTrailerOperation =
      /(тягач|седельн).{0,100}(полуприцеп|прицеп|тонар)|(полуприцеп|прицеп|тонар).{0,100}(тягач|седельн)/.test(note) &&
      /(эксплуат|работа|рейс|перевоз|парк|водител|автопоезд)/.test(note);
    const freightTrailerContext =
      /(полуприцеп|тонар|kogel|krone|schmitz|wielton|grunwald|низкорамн.{0,30}(прицеп|полуприцеп)|тяжеловозн.{0,30}(прицеп|полуприцеп)|грузов.{0,35}(прицеп|полуприцеп)|(прицеп|полуприцеп).{0,35}грузов)/i.test(note);
    const explicitTrailerProcurement =
      freightTrailerContext &&
      (
        /(закупк|тендер|поставк|приобрет|купил|куплен|контракт|договор).{0,140}(полуприцеп|прицеп|тонар|kogel|krone|schmitz|wielton|grunwald)/i.test(note) ||
        /(полуприцеп|прицеп|тонар|kogel|krone|schmitz|wielton|grunwald).{0,140}(закупк|тендер|поставк|приобрет|купил|куплен|контракт|договор)/i.test(note)
      );
    const explicitTrailerOwnership =
      freightTrailerContext &&
      (
        /(в собственности|на балансе|собственн.{0,30}парк|имеет|эксплуатирует|эксплуатаци).{0,120}(полуприцеп|прицеп|тонар|kogel|krone|schmitz|wielton|grunwald)/i.test(note) ||
        /(полуприцеп|прицеп|тонар|kogel|krone|schmitz|wielton|grunwald).{0,120}(в собственности|на балансе|собственн.{0,30}парк|имеет|эксплуатирует|эксплуатаци)/i.test(note)
      );
    // Если запись сообщает лишь об услуге/возможности ремонта, нельзя
    // выдавать её за конкретный заказ, эксплуатацию или выполненную работу.
    const genericServiceOnly =
      serviceOffering.test(note) &&
      !specificServiceEvent.test(note) &&
      (serviceMarketingOnly.test(note) || /ремонт|обслужив|сервис/.test(note)) &&
      !/(приобрел|приобретен|купил|куплен|лизинг|на балансе|эксплуатирует|собственн.{0,30}парк|вин|vin|госномер)/.test(note);
    if (genericServiceOnly) continue;

    const strongLinkedSignal =
      priorityTrailerModel.test(note) ||
      genericTrailerIdentification.test(note) ||
      ceTrailerJob.test(note) ||
      trailerFleet.test(note) ||
      trailerCommerce.test(note);

    if (
      explicitVinOrPlate ||
      tractorTrailerOperation ||
      explicitTrailerProcurement ||
      explicitTrailerOwnership ||
      strongLinkedSignal ||
      (trailer && trailerAction && /(конкретн|фактич|в собственности|на балансе|эксплуат|продаж|лизинг|ремонт|аренд)/.test(note))
    ) {
      aEvidence = note;
      break;
    }
  }

  let grade = "";
  let reason = "";

  if (aEvidence) {
    grade = "A";
    reason = "Конкретный evidence-note одновременно подтверждает прицепную/полуприцепную технику и факт сделки, владения, эксплуатации, ремонта или лизинга.";
  } else if (target && heavy) {
    grade = "B";
    reason = "В evidence одновременно подтверждены целевой груз/процесс и тяжелая автологистика или эксплуатационный сигнал.";
  } else if (target && transport) {
    grade = "C";
    reason = "В evidence подтверждены целевой груз/процесс и конкретный транспортно-логистический сигнал, но недостаточно данных для A/B.";
  } else {
    reason = target
      ? "Подтвержден целевой груз/процесс, но нет достаточного конкретного транспортного сигнала."
      : "Evidence не подтверждает достаточную коммерческую релевантность для A/B/C.";
  }

  return {
    decision: grade ? "include" : "exclude",
    grade,
    reason,
    aEvidence,
    signals: {
      target,
      priorityTarget,
      generalTarget,
      heavy,
      transport,
      aEvidence: Boolean(aEvidence)
    }
  };
}

async function runFinalQualification({
  client,
  records,
  region,
  assertNotCancelled,
  diagnosticPrefix = "final qualification"
}) {
  const decisions = new Map();
  const counts = { A: 0, B: 0, C: 0, excluded: 0 };

  for (let index = 0; index < records.length; index++) {
    if (index % 50 === 0) await assertNotCancelled();
    const record = records[index];
    const decision = deterministicQualificationDecision(record);
    decisions.set(record.id, {
      decision: decision.decision,
      grade: decision.grade,
      reason: decision.reason,
      aEvidence: decision.aEvidence || ""
    });

    if (decision.grade) counts[decision.grade]++;
    else counts.excluded++;
  }

  console.log("[DETERMINISTIC_FINAL_QUALIFICATION] " + JSON.stringify({
    prefix: diagnosticPrefix,
    region,
    total: records.length,
    A: counts.A,
    B: counts.B,
    C: counts.C,
    excluded: counts.excluded
  }));

  return decisions;
}

function applyFinalQualification(records, decisions) {
  const result = {
    direct_buyers: [],
    intermediaries: [],
    leasing: [],
    statistics: []
  };
  const counts = { A: 0, B: 0, C: 0, excluded: 0 };

  for (const record of records) {
    const decision = decisions.get(record.id);
    if (!decision || decision.decision !== "include" || !decision.grade) {
      counts.excluded++;
      continue;
    }

    const row = { ...record.row };
    row.__final_grade = decision.grade;
    row.__decision = "include";
    row.__decision_reason = decision.reason;
    row.__a_evidence = decision.grade === "A" ? String(decision.aEvidence || "") : "";
    row["Основание"] = `${decision.grade} — ${decision.reason}`;
    counts[decision.grade]++;

    result[record.sheet].push(row);
  }

  return { result, counts };
}

function buildQualificationCheckpoint(records, decisions) {
  return {
    version: 1,
    records: records.map((record) => {
      const decision = decisions.get(record.id) || {};
      return {
        id: String(record.id || ""),
        canonical_id: String(record.canonical_id || ""),
        organization: String(record?.row?.["Организация"] || ""),
        grade: String(decision.grade || ""),
        decision: String(decision.decision || "exclude"),
        reason: String(decision.reason || ""),
        a_evidence: String(decision.aEvidence || "")
      };
    })
  };
}

function compareQualificationCheckpoints(previousCheckpoint, currentCheckpoint) {
  const previous = Array.isArray(previousCheckpoint?.records)
    ? previousCheckpoint.records
    : [];
  const current = Array.isArray(currentCheckpoint?.records)
    ? currentCheckpoint.records
    : [];

  const keyFor = (item) =>
    String(item?.id || "").trim() ||
    String(item?.canonical_id || "").trim() ||
    normalizeOrgKey(item?.organization || "");

  const previousByKey = new Map(
    previous.map((item) => [keyFor(item), item]).filter(([key]) => key)
  );
  const currentByKey = new Map(
    current.map((item) => [keyFor(item), item]).filter(([key]) => key)
  );
  const transitions = {};
  const changed = [];
  let unchanged = 0;
  let added = 0;
  let removed = 0;

  for (const [key, now] of currentByKey.entries()) {
    const before = previousByKey.get(key);
    if (!before) {
      added++;
      continue;
    }

    const from = String(before.grade || "EXCLUDE").toUpperCase() || "EXCLUDE";
    const to = String(now.grade || "EXCLUDE").toUpperCase() || "EXCLUDE";

    if (from === to) {
      unchanged++;
      continue;
    }

    const transition = `${from}->${to}`;
    transitions[transition] = (transitions[transition] || 0) + 1;
    changed.push({
      id: String(now.id || before.id || ""),
      canonical_id: String(now.canonical_id || before.canonical_id || ""),
      organization: String(now.organization || before.organization || ""),
      from,
      to,
      previous_reason: String(before.reason || ""),
      current_reason: String(now.reason || "")
    });
  }

  for (const key of previousByKey.keys()) {
    if (!currentByKey.has(key)) removed++;
  }

  return {
    previous_total: previousByKey.size,
    current_total: currentByKey.size,
    unchanged,
    changed_count: changed.length,
    added,
    removed,
    transitions,
    changed
  };
}

class WebBudgetStopError extends Error {
  constructor(scope, used, limit, totalUsed, totalLimit) {
    super(`WEB_BUDGET_STOP:${scope}:${used}/${limit}:total=${totalUsed}/${totalLimit}`);
    this.name = "WebBudgetStopError";
    this.code = "WEB_BUDGET_STOP";
    this.scope = scope;
    this.used = used;
    this.limit = limit;
    this.totalUsed = totalUsed;
    this.totalLimit = totalLimit;
  }
}

function webBudgetScope(label = "") {
  const value = String(label || "").toLowerCase();
  if (value.startsWith("этап 1 |")) return "stage1";
  if (value.startsWith("этап 2 |")) return "stage2";
  if (value.startsWith("identity |")) return "identity";
  if (value.startsWith("география региона |")) return "geography";
  return "other";
}

